/* The bytes of Cookie's first compiled program, carried inside the boot image.
 *
 * docs/M7_12_FIRST_PROGRAM.md decided this: "boot places exactly one image",
 * and the reason is identity rather than convenience. seL4's elfloader takes
 * its user image from an unsigned CPIO archive beside the kernel; Cookie's boot
 * artefact already carries digests and signer lineage (M5.0), so a program that
 * travels *inside* it is measured by the same chain that measures the kernel.
 * A program the boot image merely knew how to find would be a second thing to
 * verify, and the first process is the one holding the memory authority
 * everything else derives from.
 *
 * This is the whole of the mechanism, and it is deliberately not a loader. The
 * loader - executing a .ckx plan against the syscall surface - is what this
 * program grows into; what happens here is that boot copies a flat region into
 * a page, which is the one placement that needs no parser at EL1.
 *
 * `.incbin` rather than a generated byte array: a generated source would be a
 * second representation of the same bytes, produced by a script that could
 * differ from the program the linker actually emitted. The assembler reads the
 * file the build just produced.
 *
 * COOKIE_FIRST_PROGRAM_IMAGE is the path, passed by core/oskernel/CMakeLists.txt
 * from $<TARGET_FILE:cookie_first_program>.bin. No default: a missing definition
 * must fail the build rather than embed nothing, because an image embedding
 * nothing still boots and would report the program as having run into a page of
 * zeroes.
 */

#ifndef COOKIE_FIRST_PROGRAM_IMAGE
#error "COOKIE_FIRST_PROGRAM_IMAGE was not defined; the boot image would carry no program"
#endif

    .section .rodata.cookie_first_program, "a", %progbits
    /* Instruction alignment, because these bytes are executed once copied. The
     * copy is to a page base so the destination is aligned regardless; aligning
     * the source keeps the word-at-a-time copy in aarch64_boot.cpp reading
     * aligned words on the side it does not control. */
    .balign 8
    .globl cookie_first_program_image_start
    .hidden cookie_first_program_image_start
cookie_first_program_image_start:
    .incbin COOKIE_FIRST_PROGRAM_IMAGE
    .globl cookie_first_program_image_end
    .hidden cookie_first_program_image_end
cookie_first_program_image_end:
